#!/usr/bin/env bash
# Creates the project's kind cluster (#12); run by `make kind-up`. No-op if the cluster already exists.
# Always passes --name explicitly, and restores the kube context that was current before (kind makes its own current).
#
# Opt-in local dataset (#40): with LOCAL_DATASET set, the cluster gets a read-only kind extraMount of the dataset
# directory (the one containing maildir/) at $NODE_PATH on the node, and the node label $NODE_LABEL=true. The
# kind-local-dataset overlay then exposes it to the pod through a `local` PersistentVolume. The absolute host path
# only goes into a generated config under .tools/, never into a tracked file.
#
# Environment:
#   KIND_CLUSTER       cluster name (default elisa-enron)
#   LOCAL_DATASET      unset (default): the cluster is created exactly as before.
#                      1: mount Dataset/ of the main checkout (found through git, so this works from any worktree).
#                      a path: mount that directory, which must contain maildir/. A relative path is resolved
#                      against the caller's working directory (with `make`, the directory make runs in).
#   PRINT_CONFIG       1 to print the kind config that would be used and exit (used by make k8s-validate)
set -euo pipefail

# A relative LOCAL_DATASET is relative to the caller's directory (for `make kind-up`, where make runs: the repo root).
caller_dir=$PWD
cd "$(dirname "$0")/.."
export CGO_ENABLED=0

KIND_CLUSTER=${KIND_CLUSTER:-elisa-enron}
LOCAL_DATASET=${LOCAL_DATASET:-}
[[ "$LOCAL_DATASET" == 0 ]] && LOCAL_DATASET=
BASE_CONFIG=deploy/kind/cluster.yaml
# Keep in sync with deploy/k8s/overlays/kind-local-dataset/local-dataset.yaml (make k8s-validate checks it).
NODE_PATH=/var/local/enron-dataset
NODE_LABEL=elisa-enron/local-dataset

die() {
	echo "kind-up: $*" >&2
	exit 1
}

if [[ -z "$LOCAL_DATASET" ]]; then
	config=$BASE_CONFIG
else
	dir=$LOCAL_DATASET
	if [[ "$dir" == 1 ]]; then
		# Dataset/ of the main checkout: git's common directory is <main checkout>/.git, also from a worktree.
		common=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null) ||
			die "cannot locate the main checkout; set LOCAL_DATASET=/path/to/Dataset"
		dir=$(dirname "$common")/Dataset
	elif [[ "$dir" != /* ]]; then
		dir=$caller_dir/$dir
	fi
	[[ -d "$dir/maildir" ]] ||
		die "no maildir/ directory in $dir; set LOCAL_DATASET to the directory that contains maildir/"
	# Absolute and symlink-free: kind (and Docker Desktop's file sharing) need the real host path.
	dir=$(cd "$dir" && pwd -P)
	# The tracked config plus the mount and the label, so the node image stays pinned in one place.
	local_config() {
		DIR=$dir NODE_PATH=$NODE_PATH NODE_LABEL=$NODE_LABEL go tool yq eval '
			.nodes[0].extraMounts = [{"hostPath": strenv(DIR), "containerPath": strenv(NODE_PATH), "readOnly": true}] |
			.nodes[0].labels[strenv(NODE_LABEL)] = "true" |
			. head_comment = "Generated by scripts/kind-up.sh from deploy/kind/cluster.yaml (LOCAL_DATASET); do not edit."
		' "$BASE_CONFIG"
	}
	if [[ "${PRINT_CONFIG:-}" == 1 ]]; then
		local_config
		exit 0
	fi
	mkdir -p .tools/kind
	config=.tools/kind/cluster-local-dataset.yaml
	local_config >"$config.tmp"
	mv "$config.tmp" "$config"
fi

if [[ "${PRINT_CONFIG:-}" == 1 ]]; then
	cat "$config"
	exit 0
fi

command -v kind >/dev/null || die "kind not found on PATH (prerequisite, see README)"
command -v kubectl >/dev/null || die "kubectl not found on PATH (prerequisite, see README)"

if kind get clusters 2>/dev/null | grep -qx "$KIND_CLUSTER"; then
	echo "kind cluster $KIND_CLUSTER already exists"
	if [[ -n "$LOCAL_DATASET" ]]; then
		# extraMounts can only be set when a cluster is created.
		src=$(docker inspect --format "{{range .Mounts}}{{if eq .Destination \"$NODE_PATH\"}}{{.Source}}{{end}}{{end}}" \
			"$KIND_CLUSTER-control-plane" 2>/dev/null || true)
		# Docker Desktop reports host paths under its file-sharing root.
		src=${src#/host_mnt}
		if [[ -z "$src" ]]; then
			die "cluster $KIND_CLUSTER was created without LOCAL_DATASET; recreate it: make kind-down kind-up LOCAL_DATASET=1"
		elif [[ "$src" != "$dir" ]]; then
			echo "kind-up: note: the cluster mounts $src, not $dir; run make kind-down first to change it" >&2
		else
			echo "kind-up: it mounts the local dataset $src"
		fi
	fi
	exit 0
fi

prev=$(kubectl config current-context 2>/dev/null || true)
if [[ -n "$LOCAL_DATASET" ]]; then
	echo "kind-up: mounting $dir read-only at $NODE_PATH on the node (config $config)"
fi
kind create cluster --name "$KIND_CLUSTER" --config "$config" --wait 120s
if [[ -n "$prev" ]]; then
	kubectl config use-context "$prev" >/dev/null
	echo "restored current kube context to $prev (use --context kind-$KIND_CLUSTER)"
else
	kubectl config unset current-context >/dev/null
	echo "no current kube context before; left unset (use --context kind-$KIND_CLUSTER)"
fi
